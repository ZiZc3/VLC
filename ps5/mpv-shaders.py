#!/usr/bin/env python3
"""mpv user shaders (third_party/mpv-shaders) -> Vulkan fragment shaders and a
table of their passes, for src/mpvshader.cc. Run by compile-shaders.sh.

mpv's format (its manual, "USER SHADERS"): passes separated by //!HOOK
lines, each with directives (//!BIND name, //!SAVE name, //!WIDTH and
//!HEIGHT as reverse-Polish expressions, //!WHEN, //!COMPONENTS, //!DESC)
and GLSL with a vec4 hook(). Each bound texture NAME gets macros: NAME_tex,
NAME_texOff, NAME_pos, NAME_size, NAME_pt, NAME_mul... This writes one
fragment shader per pass with those macros, compiles it to SPIR-V with
glslangValidator, and lists the passes (their names, sizes and conditions)
in src/gen/mpv_shaders.h. The shader code itself is left as its authors
wrote it.

The sets (what the player's menu offers):
  fsrcnnx     FSRCNNX x2 8-0-4-1 (igv; LGPL-3.0)
  a4k_light   Anime4K Restore CNN M + Upscale CNN x2 M (bloc97; MIT)
  a4k_heavy   Anime4K Restore CNN VL + Upscale CNN x2 VL
  a4k_medium  Anime4K Restore CNN M + Upscale CNN x2 VL (a fast video the heavy can't keep up with)
"""
import os
import re
import subprocess
import sys

repo = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
src_dir = os.path.join(repo, 'third_party', 'mpv-shaders')
gen_dir = os.path.join(repo, 'src', 'gen', 'mpv')
out_h = os.path.join(repo, 'src', 'gen', 'mpv_shaders.h')

SETS = [
    ('fsrcnnx', ['fsrcnnx/FSRCNNX_x2_8-0-4-1.glsl']),
    ('a4k_light', ['anime4k/Anime4K_Restore_CNN_M.glsl', 'anime4k/Anime4K_Upscale_CNN_x2_M.glsl']),
    ('a4k_heavy', ['anime4k/Anime4K_Restore_CNN_VL.glsl', 'anime4k/Anime4K_Upscale_CNN_x2_VL.glsl']),
    ('a4k_medium', ['anime4k/Anime4K_Restore_CNN_M.glsl', 'anime4k/Anime4K_Upscale_CNN_x2_VL.glsl']),
]
MAX_BINDS = 16


def parse(path):
    """The passes of one mpv shader file."""
    passes = []
    cur = None
    for line in open(path, encoding='utf-8'):
        m = re.match(r'\s*//!(\w+)\s*(.*?)\s*$', line)
        if m:
            key, val = m.group(1).upper(), m.group(2)
            if cur is None or cur['code_started']:
                cur = {'hook': None, 'binds': [], 'save': '', 'width': '', 'height': '', 'when': '',
                       'desc': '', 'code': [], 'code_started': False}
                passes.append(cur)
            if key == 'HOOK':
                cur['hook'] = val
            elif key == 'BIND':
                cur['binds'].append(val)
            elif key == 'SAVE':
                cur['save'] = val
            elif key == 'WIDTH':
                cur['width'] = val
            elif key == 'HEIGHT':
                cur['height'] = val
            elif key == 'WHEN':
                cur['when'] = val
            elif key == 'DESC':
                cur['desc'] = val
            elif key in ('COMPONENTS', 'OFFSET'):
                pass  # every image is RGBA 16-bit float here
            else:
                sys.exit('%s: //!%s is not supported' % (path, key))
            continue
        if cur is not None:
            if line.strip() or cur['code_started']:
                cur['code_started'] = True
                cur['code'].append(line)
    for p in passes:
        if not p['hook']:
            sys.exit('%s: a pass without //!HOOK' % path)
        if len(p['binds']) > MAX_BINDS:
            sys.exit('%s: more than %d textures in one pass' % (path, MAX_BINDS))
    return passes


def glsl(p):
    """One pass as a Vulkan fragment shader with mpv's macros."""
    out = ['#version 450', '// generated by ps5/mpv-shaders.py from an mpv user shader: do not edit',
           'layout(location = 0) out vec4 mpv_out;',
           'layout(push_constant) uniform MpvPush {',
           '    vec4 out_size;      // this pass: width, height, 1/width, 1/height',
           '    vec4 target;        // the picture\'s final size (OUTPUT): width, height',
           '} mp;',
           '#define target_size (mp.target.xy)',
           '#define frame 0',
           '#define random 0.5']
    for i, name in enumerate(p['binds']):
        out += ['layout(set = 0, binding = %d) uniform sampler2D %s_raw;' % (i, name),
                '#define %s_size vec2(textureSize(%s_raw, 0))' % (name, name),
                '#define %s_pt (1.0 / %s_size)' % (name, name),
                '#define %s_pos (gl_FragCoord.xy * mp.out_size.zw)' % name,
                '#define %s_mul 1.0' % name,
                '#define %s_off vec2(0.0)' % name,
                '#define %s_rot mat2(1.0)' % name,
                '#define %s_tex(pos) (texture(%s_raw, (pos)) * %s_mul)' % (name, name, name),
                '#define %s_texOff(off) %s_tex(%s_pos + %s_pt * (off))' % (name, name, name, name),
                '#define %s_gather(pos, c) (textureGather(%s_raw, (pos), (c)) * %s_mul)' % (name, name, name)]
    out += [''.join(p['code']).rstrip(), '', 'void main()', '{', '    mpv_out = hook();', '}', '']
    return '\n'.join(out)


def c_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    os.makedirs(gen_dir, exist_ok=True)
    includes, tables = [], []
    newest_src = max(os.path.getmtime(os.path.join(src_dir, f)) for _, fs in SETS for f in fs)
    newest_src = max(newest_src, os.path.getmtime(__file__))
    up_to_date = os.path.exists(out_h) and os.path.getmtime(out_h) >= newest_src
    for set_name, files in SETS:
        rows = []
        n = 0
        for f in files:
            for p in parse(os.path.join(src_dir, f)):
                base = '%s_%d' % (set_name, n)
                frag = os.path.join(gen_dir, base + '.frag')
                h = os.path.join(gen_dir, base + '.h')
                if not up_to_date or not os.path.exists(h):
                    open(frag, 'w', encoding='utf-8', newline='\n').write(glsl(p))
                    r = subprocess.run(['glslangValidator', '-V', '--target-env', 'vulkan1.1',
                                        '--vn', 'spv_mpv_' + base, frag, '-o', h],
                                       capture_output=True, text=True)
                    if r.returncode != 0:
                        sys.exit('%s (%s): %s' % (f, p['desc'], r.stdout + r.stderr))
                includes.append('#include "mpv/%s.h"' % base)
                binds = ', '.join(c_str(b) for b in p['binds'])
                rows.append('    { spv_mpv_%s, sizeof(spv_mpv_%s), %s, { %s }, %d, %s, %s, %s, %s, %s },' % (
                    base, base, c_str(p['hook']), binds, len(p['binds']), c_str(p['save']),
                    c_str(p['width']), c_str(p['height']), c_str(p['when']), c_str(p['desc'])))
                n += 1
        tables.append((set_name, rows))
    with open(out_h, 'w', encoding='utf-8', newline='\n') as o:
        o.write('// generated by ps5/mpv-shaders.py: the mpv user shaders\' passes\n#pragma once\n')
        o.write('#include <stddef.h>\n#include <stdint.h>\n')
        o.write('\n'.join(includes) + '\n\n')
        o.write('struct MpvPassInfo {\n    const uint32_t *spv;\n    size_t size;\n    const char *hook;\n'
                '    const char *binds[%d];\n    int nbinds;\n    const char *save;\n'
                '    const char *width, *height, *when;  /* reverse Polish, "" for none */\n'
                '    const char *desc;\n};\n\n' % MAX_BINDS)
        for set_name, rows in tables:
            o.write('static const MpvPassInfo mpv_set_%s[] = {\n%s\n};\n' % (set_name, '\n'.join(rows)))
    print('mpv shaders: ' + ', '.join('%s %d passes' % (s, len(r)) for s, r in tables))


main()
